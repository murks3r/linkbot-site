/* One palette for the site and the app. The app's tools/design/palette.cjs generates and proves
   the colour tokens (every text and control pair meets its contrast minimum); this copies that
   generated block into the site, unchanged, so the two can never drift apart by hand.

     node scripts/sync-tokens.mjs <path to a murks3r/linkbot checkout>           copy
     node scripts/sync-tokens.mjs <path to a murks3r/linkbot checkout> --check   exit 1 if different */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const [app, mode] = process.argv.slice(2);
if (!app) { console.error('usage: sync-tokens.mjs <app checkout> [--check]'); process.exit(2); }
const BEGIN = '/* palette:begin */', END = '/* palette:end */';
const source = readFileSync(path.join(app, 'frontend/src/design/system/tokens.css'), 'utf8');
const block = source.slice(source.indexOf(BEGIN), source.indexOf(END) + END.length);
if (!block.startsWith(BEGIN)) throw Error('no palette block in the app tokens');
const commit = execFileSync('git', ['-C', app, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const target = new URL('../src/styles/palette.css', import.meta.url);
const next = `/* Generated by scripts/sync-tokens.mjs from murks3r/linkbot frontend/src/design/system/tokens.css
   (tools/design/palette.cjs proves every pair). Do not edit by hand. Source commit: ${commit} */
:root {
  ${block}
}
`;
const strip = css => css.replace(/Source commit: [0-9a-f]+/, '');
if (mode === '--check') {
  const current = readFileSync(target, 'utf8');
  if (strip(current) !== strip(next)) { console.error('src/styles/palette.css differs from the app palette; run scripts/sync-tokens.mjs'); process.exit(1); }
  console.log('palette in sync with', commit);
} else { writeFileSync(target, next); console.log('palette copied from', commit); }

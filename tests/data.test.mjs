/* The recorded interpreter readings and the copied palette are evidence, so they are checked:
   every read phrase sits inside its sentence and quotes it exactly, every reading names the
   commit that produced it, and nothing interpreted is presented as unchanged when it was not. */
import assert from 'node:assert/strict';
import test from 'node:test';
import { readFileSync } from 'node:fs';

const record = JSON.parse(readFileSync(new URL('../src/data/readings.json', import.meta.url)));

test('readings name the app commit that produced them, from a clean interpreter', () => {
  assert.match(record.commit, /^[0-9a-f]{40}$/);
  assert.equal(record.interpreterChanged, false, 're-record the readings from a committed interpreter');
});

test('every reading span quotes its sentence exactly, in order, without overlap', () => {
  for (const reading of record.readings) {
    let end = 0;
    for (const span of reading.spans) {
      assert.ok(span.start >= end && span.end <= reading.text.length, `${reading.id}: span out of order or bounds`);
      assert.equal(reading.text.slice(span.start, span.end), span.quote, `${reading.id}: quote mismatch`);
      assert.ok(['read', 'unused', 'off', 'choose'].includes(span.tone));
      end = span.end;
    }
  }
});

test('only understood phrases are set as read; the paragraph reads to nothing', () => {
  const by = Object.fromEntries(record.readings.map(r => [r.id, r]));
  assert.equal(by.paragraph.criteria.length, 0);
  assert.ok(by.paragraph.spans.every(s => s.tone === 'unused'));
  assert.deepEqual(by.unknown.unused.map(u => u.text), ['React']);
  for (const r of record.readings) assert.equal(r.spans.filter(s => s.tone === 'read').length, r.criteria.length, `${r.id}: one read phrase per criterion`);
});

test('the palette copy is the app’s generated block', () => {
  const css = readFileSync(new URL('../src/styles/palette.css', import.meta.url), 'utf8');
  assert.match(css, /Generated by scripts\/sync-tokens\.mjs/);
  // Concept A4: green ink and a pink spot colour on warm paper; the highlighter is gone.
  assert.match(css, /--lb-cream: #fbf8f1;/);
  assert.match(css, /--lb-forest: #123a2c;/);
  assert.match(css, /--lb-pink: #ff9dbb;/);
  assert.doesNotMatch(css, /--lb-sun/);
  assert.match(css, /Source commit: [0-9a-f]{40}/);
});

test('the homepage story is read in full by the interpreter', () => {
  const story = record.readings.find(r => r.id === 'story');
  assert.ok(story, 'the story reading is recorded');
  assert.equal(story.unused.length, 0);
  assert.deepEqual(story.criteria.map(c => `${c.dimension}:${c.label}:${c.level}`),
    ['role_direction:Product designer:prefer', 'work_mode:Hybrid:prefer', 'task:more research:prefer', 'task:agency work:avoid']);
});

test('every example and placeholder the site offers is read in full', () => {
  assert.deepEqual(record.examples.map(e => e.id), ['hero-placeholder', 'start-placeholder', 'start-1', 'start-2', 'start-3']);
  for (const e of record.examples) {
    assert.equal(e.unused.length, 0, `${e.id}: “${e.text}” leaves words unused`);
    assert.ok(e.criteria.length >= 2, `${e.id}: “${e.text}” reads to fewer than two criteria`);
    assert.ok(e.criteria.some(c => c.dimension === 'role_direction'), `${e.id}: “${e.text}” names no role Linkbot reads`);
  }
});

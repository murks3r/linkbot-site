/* The palette is copied from the app's generated tokens (scripts/sync-tokens.mjs), so the copy is
   checked: it is the generated block, with the colours the design is built on, and it names the
   app commit it came from. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

test('the palette copy is the app’s generated block', () => {
  const css = readFileSync(new URL('../src/styles/palette.css', import.meta.url), 'utf8');
  assert.match(css, /Generated by scripts\/sync-tokens\.mjs/);
  // Green ink and a pink spot colour on warm paper; the highlighter is gone.
  assert.match(css, /--lb-cream: #fbf8f1;/);
  assert.match(css, /--lb-forest: #123a2c;/);
  assert.match(css, /--lb-pink: #ff9dbb;/);
  assert.doesNotMatch(css, /--lb-sun/);
  assert.match(css, /Source commit: [0-9a-f]{40}/);
});
